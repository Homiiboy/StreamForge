import assert from 'node:assert/strict';
import {parseSeasonFolder,findSeriesFolder,discoverSeasons,checkedSeasonFolder} from '../season-discovery.js';
const dir=(name,children={})=>({name,kind:'directory',async queryPermission(){return 'granted'},async *entries(){for(const [n,h] of Object.entries(children))yield [n,h]}});
const s1=dir('Season 01'),s2=dir('Staffel 2'),extras=dir('Specials');
const series=dir('Slugterra',{'Season 01':s1,'Staffel 2':s2,Specials:extras,'notes.txt':{kind:'file'}});
const root=dir('root',{Shows:dir('Shows',{Slugterra:series})});
assert.equal(parseSeasonFolder('Season 02'),2);
assert.equal(parseSeasonFolder('staffel_003'),3);
assert.equal(parseSeasonFolder('Specials'),0);
assert.equal(parseSeasonFolder('random'),null);
assert.deepEqual((await discoverSeasons(root,{title:'Slugterra'})).map(x=>x.number),[0,1,2]);
assert.equal((await discoverSeasons(root,{title:'Slugterra'}))[2].name,'Staffel 2');
assert.deepEqual(await discoverSeasons(root,{title:'Missing'}),[]);
assert.equal(await findSeriesFolder(root,{placement:'library',title:'Slugterra'}),series);
assert.deepEqual((await discoverSeasons(series,{placement:'series'})).map(x=>x.number),[0,1,2]);
assert.deepEqual(await discoverSeasons(s2,{placement:'season'}),[{number:2,name:'Staffel 2'}]);
assert.equal(checkedSeasonFolder('Staffel 2',2),'Staffel 2');
assert.throws(()=>checkedSeasonFolder('Season 01',2),/passt nicht/);
console.log('Season folder discovery tests passed');
