import assert from 'node:assert/strict';
import { DownloadQueue } from '../download-queue.js';

const q = new DownloadQueue();
const events = [];
let release;
const gate = new Promise(resolve => { release = resolve; });
const first = q.enqueue(async () => { events.push('first-start'); await gate; events.push('first-end'); return 1; });
const second = q.enqueue(async () => { events.push('second-start'); throw new Error('expected failure'); });
const failed = assert.rejects(second.promise, /expected failure/);
const third = q.enqueue(async () => { events.push('third-start'); return 3; });
assert.equal(first.position, 0);
assert.equal(second.position, 1);
assert.equal(third.position, 2);
assert.equal(q.waiting, 2);
assert.deepEqual(events, ['first-start']);
release();
assert.equal(await first.promise, 1);
await failed;
assert.equal(await third.promise, 3);
assert.deepEqual(events, ['first-start', 'first-end', 'second-start', 'third-start']);
assert.equal(q.busy, false);
assert.equal(q.waiting, 0);
assert.throws(() => q.enqueue(null), TypeError);
const cancelQueue = new DownloadQueue();
let unblock;
const hold = cancelQueue.enqueue(() => new Promise(resolve => { unblock=resolve; }), 'active');
const pending = cancelQueue.enqueue(() => { throw Error('cancelled task ran'); }, 'queued');
const cancelError=assert.rejects(pending.promise, error => error.code === 'QUEUE_CANCELLED');
assert.equal(cancelQueue.cancel('queued'),true);
assert.equal(cancelQueue.cancel('queued'),false);
assert.equal(cancelQueue.cancel('active'),false);
await cancelError;
unblock();
await hold.promise;
assert.equal(cancelQueue.waiting,0);
console.log('DownloadQueue tests passed');
